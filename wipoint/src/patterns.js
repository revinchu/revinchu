/** 무늬 → SVG <path d> (전경 픽셀), 한 칸 = 1 */
export function patternPath(prst) {
  const rows = PATTERNS[prst] ?? PATTERNS.pct50;
  let d = '';
  rows.forEach((bits, y) => {
    for (let x = 0; x < 8; x++) {
      if (!(bits & (0x80 >> x))) continue;
      let n = 1;
      while (x + n < 8 && bits & (0x80 >> (x + n))) n++;
      d += `M${x} ${y}h${n}v1h-${n}z`;
      x += n - 1;
    }
  });
  return d;
}

/** 무늬 한 칸 SVG (CSS 배경 · 미리 보기용 data URL), fg · bg = CSS 색 */
export function patternSvgUrl(prst, fg, bg, cell = 1) {
  const s = 8 * cell;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 8 8" shape-rendering="crispEdges"><rect width="8" height="8" fill="${bg}"/><path d="${patternPath(prst)}" fill="${fg}"/></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}
