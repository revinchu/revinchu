export function objectStyleFillCss(st) {
  const color=v=>/^#[0-9a-f]{6}$/i.test(v??'')?v:undefined;
  const g=st.gradient;
  if(g?.stops?.length&&g.stops.every(p=>Array.isArray(p)&&Number.isFinite(p[0])&&color(p[1]))) {
    const stops=g.stops.map(([p,c])=>`${c} ${p*100}%`).join(', ');
    if(g.path)return `radial-gradient(farthest-corner at ${((Number(g.l)||0)+(Number(g.r)||0))*50}% ${((Number(g.t)||0)+(Number(g.b)||0))*50}%, ${stops})`;
    return `linear-gradient(${(Number(g.deg)||0)+90}deg, ${stops})`;
  }
  const bits=PATTERN_BITS[st.pattern];
  if(bits){let d='';bits.forEach((row,y)=>{for(let x=0;x<8;x++)if(row[x]==='1')d+=`M${x} ${y}h1v1h-1z`;});
    const svg=`<svg xmlns='http://www.w3.org/2000/svg' width='8' height='8' shape-rendering='crispEdges'>${color(st.fill)?`<rect width='8' height='8' fill='${color(st.fill)}'/>`:''}<path d='${d}' fill='${color(st.patternColor)??'#000000'}'/></svg>`;
    return `url(data:image/svg+xml,${encodeURIComponent(svg).replace(/['()]/g,ch=>'%'+ch.charCodeAt(0).toString(16))}) 0 0 / 8px 8px`;
  }
  return st.fill===null?'transparent':color(st.fill);
}
