// 대화상자·메뉴 접근키. 자동 배정은 WIXEL의 탐색 편의 기능이며 Excel 키와 같다는 뜻은 아니다.
export function accessKeyFromLabel(label) {
  const text = String(label ?? '');
  const parenthesized = /\(\s*&?([A-Z0-9])\s*\)/i.exec(text);
  if (parenthesized) return parenthesized[1].toLowerCase();
  const ampersand = /(?:^|[^&])&([A-Z0-9])/i.exec(text);
  return ampersand ? ampersand[1].toLowerCase() : '';
}

export function accessKeyFromEvent(event) {
  if (event.ctrlKey || event.metaKey || event.getModifierState?.('AltGraph')) return '';
  const physical = /^Key([A-Z])$|^Digit([0-9])$/.exec(event.code ?? '');
  if (physical) return (physical[1] ?? physical[2]).toLowerCase();
  // 물리 code가 없는 합성/보조 장치의 조합 입력은 추정하지 않는다.
  if (event.isComposing || event.keyCode === 229) return '';
  return /^[a-z0-9]$/i.test(event.key ?? '') ? event.key.toLowerCase() : '';
}

/** 공통 창 기본 키. 개별 창에서 지정한 키는 호출부에서 우선한다. */
export function dialogButtonAccessKey(label) {
  const text = String(label ?? '').replace(/\s*\(\s*&?[a-z0-9]\s*\)\s*/gi, '').trim();
  return { '확인': 'o', '취소': 'c', '닫기': 'd' }[text] ?? '';
}

