// Natural Earth v5.1.2 공개 영역 데이터에서 오프라인 SVG 좌표를 재생성합니다.
// 실행에는 네트워크가 필요하지만 앱 실행/지도 렌더링에는 네트워크가 필요하지 않습니다.
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const base = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/';
const names = ['ne_110m_admin_0_countries.geojson', 'ne_110m_admin_0_tiny_countries.geojson'];
const source = [];
for (const name of names) {
  const response = await fetch(base + name, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${name}: ${response.status}`);
  const bytes = new Uint8Array(await response.arrayBuffer());
  source.push({ url: base + name, sha256: createHash('sha256').update(bytes).digest('hex'), data: JSON.parse(new TextDecoder().decode(bytes)) });
}
const table = new Map(), codes = new Map();
const valid = (code, n) => new RegExp('^[A-Z]{' + n + '}$').test(code ?? '');
const round = n => Math.round(n * 100) / 100;
function add(feature, tiny) {
  const p = feature.properties, id = p.ADM0_A3;
  const iso2 = valid(p.ISO_A2_EH, 2) ? p.ISO_A2_EH : valid(p.ISO_A2, 2) ? p.ISO_A2 : '';
  const iso3 = valid(p.ISO_A3_EH, 3) ? p.ISO_A3_EH : valid(p.ISO_A3, 3) ? p.ISO_A3 : id;
  const aliases = [p.NAME, p.NAME_LONG, p.NAME_EN, p.NAME_KO, p.ADMIN, p.BRK_NAME].filter(Boolean);
  let row = table.get(id);
  if (!row) { row = { id, iso2: '', iso3, ko: p.NAME_KO || p.NAME_EN, en: p.NAME_EN, aliases: [], path: '', points: [], label: [round(p.LABEL_X ?? 0), round(p.LABEL_Y ?? 0)] }; table.set(id, row); }
  // Ascension 등 일부 tiny record의 상위 국가 ISO 코드가 다른 나라에 붙지 않도록 합니다.
  if (iso2 && (!codes.has(iso2) || codes.get(iso2) === id) && (!row.iso2 || row.iso2 === iso2)) {
    row.iso2 = iso2; codes.set(iso2, id);
    if (tiny && iso3 === id) { row.iso3 = iso3; row.ko = p.NAME_KO || row.ko; row.en = p.NAME_EN || row.en; }
  }
  row.aliases.push(...aliases.filter(a => !row.aliases.includes(a)));
  if (tiny) row.points.push(feature.geometry.coordinates.map(round));
  else {
    const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
    row.path = polygons.map(poly => poly.map(ring => ring.map(([x, y], i) => (i ? 'L' : 'M') + round(x + 180) + ',' + round(90 - y)).join('') + 'Z').join('')).join('');
  }
}
for (const f of source[0].data.features) add(f, false);
for (const f of source[1].data.features) add(f, true);
const rows = [...table.values()];
const metadata = source.map(({ url, sha256, data }) => ({ url, sha256, features: data.features.length }));
const output = `// Generated by tools/update-map-data.mjs. Natural Earth v5.1.2, public domain.\n// Coordinates are equirectangular (longitude + 180, 90 - latitude), rounded to 0.01 degrees.\n// 국가/지역 경계는 데이터 원본 기준이며 행정구역·주소 지오코딩 자료가 아닙니다.\nexport const MAP_DATA_SOURCES = ${JSON.stringify(metadata)};\nexport const MAP_COUNTRIES = ${JSON.stringify(rows)};\n`;
await writeFile(new URL('../src/chart-map-data.js', import.meta.url), output, 'utf8');
console.log(JSON.stringify({ regions: rows.length, polygonRegions: rows.filter(r => r.path).length, markers: rows.reduce((n, r) => n + r.points.length, 0), bytes: Buffer.byteLength(output), sources: metadata }));
